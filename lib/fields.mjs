/**
 * 领域地名志：一份「可以去看的地方」的清单，用来生成新的素材。
 *
 * ## 为什么需要它
 *
 * 内置语料是固定的 115 条，`serendipity_learn` 只能补上模型**恰好遇到**的东西。
 * 于是「随机素材」的自由度实际上被两件事锁住了：库有多大，以及模型这轮搜索
 * 恰好点开了什么。真实会话里最能说明问题的一幕是：用户要求「抽点最新的、随机的素材」，
 * 结果拿到什么完全取决于搜索引擎返回了什么——**随机的方向由别人决定**。
 *
 * 这份地名志把随机权拿回来：它是一份**具体学科/工种/行当**的清单，与结构核心
 * （`lib/structure-tags.mjs` 的受控词表）随机配对，交给模型一个生成任务——
 * 「去『消防工程』里找一件体现『阈值 + 延迟』的事，写出它的机理」。
 * 素材的作者成本是零（模型自己写），来源面却是无界的（这份表可以一直加）。
 *
 * ## 收录标准
 *
 * - **必须具体**。「化学」不是一个领域，「界面化学」「电镀」「制皂」是。
 *   领域越具体，里面的做法越具体，映射到别处时越不容易退化成空话。
 * - **必须真实存在、能被检索**。这些名字要能直接当关键词用。
 * - **优先选「有工艺、有操作规程、有失败案例」的行当**。
 *   实测结论：实践者踩过的坑比抽象原理更有用——它自带「不要做什么」的判据。
 * - 与内置语料已有的来源领域重复不致命（抽样时会按词元重叠避让），
 *   但**新领域应优先补进来**：`origin` 是「远不远」的唯一信号。
 *
 * @module @1603801678/dsh-serendipity/fields
 */

