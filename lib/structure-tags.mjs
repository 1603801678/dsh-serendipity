/**
 * 结构标签的受控词表。
 *
 * 为什么需要它：素材的 `structureTags` 是**跨域检索与去重的骨架**——抽取时靠它保证
 * 「一次抽取里的结构尽量不同」，`bias` 也靠它表达倾向。但如果每条素材都自造标签，
 * 骨架就会碎成几百个小簇（实测 115 条素材出现了 245 个标签，其中大部分只出现一次），
 * 检索、统计和多样性控制全部失效。
 *
 * 因此分两层：
 * - **受控核心**（这份文件）：约 40 个跨领域可迁移的「结构形状」，是检索与统计的单位。
 * - **细节标签**：素材可以写得更细，但必须能在下面的 `TAG_ALIASES` 里映射到某个受控核心；
 *   映射不上就报错——这逼着新增素材时先想清楚「它属于哪种结构」。
 *
 * 新增标签的流程：先在 `TAG_ALIASES` 里加一条映射；只有当某个结构既无法归入现有核心、
 * 又确实会在别的领域反复出现时，才往 `CONTROLLED` 里加新核心。
 *
 * 本文件由 `tools/build-corpus.mjs` 的受控词表校验与 `tools/lint-corpus.mjs` 共同把关：
 * 任何未归一的标签都会让 `npm run lint:corpus` 报 FAIL。
 *
 * @module @1603801678/dsh-serendipity/structure-tags
 */

