/**
 * 把一个（可能很细的）标签归一到受控核心。
 * @param {string} tag - 素材里写的标签。
 * @returns {string | undefined} 受控核心，未收录时返回 undefined。
 */
export function toControlled(tag) {
  if (CONTROLLED_STRUCTURE_TAGS.has(tag)) return tag
  return TAG_ALIASES[tag]
}

/**
 * 一组标签的受控核心集合。
 * @param {string[]} tags - 素材的 structureTags。
 * @returns {string[]} 去重后的受控核心。
 */
export function controlledOf(tags) {
  const result = new Set()
  for (const tag of tags) {
    const controlled = toControlled(tag)
    if (controlled !== undefined) result.add(controlled)
  }
  return [...result]
}
